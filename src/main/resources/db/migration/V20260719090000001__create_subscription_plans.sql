CREATE TABLE subscription_plan (
    id uuid PRIMARY KEY,
    code varchar(40) NOT NULL,
    name varchar(100) NOT NULL,
    price_monthly numeric(10, 2) NOT NULL DEFAULT 0,
    active boolean NOT NULL DEFAULT true,
    display_order integer NOT NULL DEFAULT 0,
    CONSTRAINT uk_subscription_plan_code UNIQUE (code),
    CONSTRAINT ck_subscription_plan_price CHECK (price_monthly >= 0)
);

CREATE TABLE subscription_plan_limit (
    id uuid PRIMARY KEY,
    plan uuid NOT NULL,
    resource varchar(80) NOT NULL,
    limit_value bigint,
    warning_percentage integer NOT NULL DEFAULT 80,
    CONSTRAINT fk_subscription_plan_limit_plan FOREIGN KEY (plan) REFERENCES subscription_plan(id) ON DELETE CASCADE,
    CONSTRAINT uk_subscription_plan_limit UNIQUE (plan, resource),
    CONSTRAINT ck_subscription_plan_limit_value CHECK (limit_value IS NULL OR limit_value >= 0),
    CONSTRAINT ck_subscription_plan_limit_warning CHECK (warning_percentage BETWEEN 1 AND 100)
);

CREATE INDEX idx_subscription_plan_limit_plan ON subscription_plan_limit(plan);

CREATE TABLE subscription_plan_feature (
    id uuid PRIMARY KEY,
    plan uuid NOT NULL,
    feature varchar(80) NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    CONSTRAINT fk_subscription_plan_feature_plan FOREIGN KEY (plan) REFERENCES subscription_plan(id) ON DELETE CASCADE,
    CONSTRAINT uk_subscription_plan_feature UNIQUE (plan, feature)
);

CREATE INDEX idx_subscription_plan_feature_plan ON subscription_plan_feature(plan);

CREATE TABLE tenant_subscription (
    id uuid PRIMARY KEY,
    tenant varchar(120) NOT NULL,
    plan uuid NOT NULL,
    status varchar(30) NOT NULL DEFAULT 'ACTIVE',
    started_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    current_period_ends_at timestamp,
    grace_period_ends_at timestamp,
    price_monthly numeric(10, 2) NOT NULL DEFAULT 0,
    price_locked_until timestamp,
    CONSTRAINT fk_tenant_subscription_plan FOREIGN KEY (plan) REFERENCES subscription_plan(id),
    CONSTRAINT uk_tenant_subscription_tenant UNIQUE (tenant),
    CONSTRAINT ck_tenant_subscription_status CHECK (status IN ('ACTIVE', 'TRIAL', 'PAST_DUE', 'GRACE_PERIOD', 'SUSPENDED', 'CANCELLED')),
    CONSTRAINT ck_tenant_subscription_price CHECK (price_monthly >= 0)
);

CREATE INDEX idx_tenant_subscription_plan ON tenant_subscription(plan);

